my_bit Key[LEN],M[LEN],subKey[TIMES][LEN],res[LEN],C[LEN];

void rotl(my_bit arr[],int len,int shift){
	my_bit tmp[LEN];
	for(int i=0;i<len;++i) tmp[i] = arr[(i+shift)%len];
	for(int i=0;i<len;++i) arr[i] = tmp[i];
	return ;
}

void solve(uint_64 n,my_bit K[]){
	for(int i=0;i<LEN;++i){
		K[63-i] = (n>>i) & 1;
	}
	return ;
}

void solve_subKey(){
	for(int i=0;i<56;++i){
		res[i] = Key[PC_1[i]];
	}

	my_bit C[28],D[28];
	
	for(int cnt=0;cnt<TIMES;++cnt){
		//copy C,D
		for(int i=0;i<28;++i){
			C[i] = res[i];
			D[i] = res[i+28];
		}
		//ROL
		rotl(C,28,mov[cnt]);
		rotl(D,28,mov[cnt]);

		for(int i=0;i<28;++i){
			res[i] = C[i];
			res[i+28] = D[i];
		}

		for(int i=0;i<48;++i){
			subKey[cnt][i] = res[PC_2[i]];
		}

	}
	return ;
}

void solve_IP(){
	my_bit tmp[LEN];
	for(int i=0;i<LEN;++i){
		tmp[i] = M[IP_Table[i]];
	}
	for(int i=0;i<LEN;++i) M[i] = tmp[i];
	return ;
}

void funcF(my_bit r[],my_bit k[],my_bit out[]){
	my_bit e[48];
	my_bit b[48];
	my_bit sout[LEN/2];
	//e expand
	for(int i=0;i<48;++i) e[i] = r[E_Table[i]];
	//xor subKey
	for(int i=0;i<48;++i) b[i] = e[i]^k[i];
	//S box
	for(int i=0;i<8;++i){
		int row = (b[i*6]<<1) | b[i*6+5];
		int col = (b[i*6+1]<<3) | (b[i*6+2]<<2) | (b[i*6+3]<<1) | (b[i*6+4]);
		int val = S[i][row][col];

		sout[i*4] = (val>>3)& 1;
		sout[i*4+1] = (val>>2) & 1;
		sout[i*4+2] = (val>>1) & 1;
		sout[i*4+3] = (val)&1;
	}
	//P permute
	for(int i=0;i<32;++i) out[i] = sout[P_Table[i]];

	return ;
}

void enc(){
	my_bit l[LEN/2],r[LEN/2],tmp[LEN/2];

	for(int i=0;i<32;++i){
		l[i] = M[i];
		r[i] = M[i+LEN/2];
	}

	for(int cnt=0;cnt<TIMES;++cnt){
		for(int i=0;i<LEN/2;++i) tmp[i] = r[i];

		my_bit fout[LEN/2];
		funcF(r,subKey[cnt],fout);

		for(int i=0;i<LEN/2;++i) r[i] = l[i]^fout[i];
		for(int i=0;i<LEN/2;++i) l[i] = tmp[i];
	}

	for(int i=0;i<LEN/2;++i){
		C[i] = r[i];
		C[i+32] = l[i];
	}

	for(int i=0;i<LEN;++i) tmp[i] = C[IP_1_Table[i]];

	for(int i=0;i<LEN;++i) C[i] = tmp[i];
	return ;
}

